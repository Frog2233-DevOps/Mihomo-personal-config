#!/usr/bin/env bash
# =============================================================================
#  make-lite.sh - build RU-Mihomo-lite.yaml from RU-Mihomo.yaml
# =============================================================================
#  The lite variant is the full config WITHOUT the ad-blocking rule-set.
#  Reason: anti-AD is about 102 000 domains and costs roughly 4 MB of RAM.
#  Measured on a Cudy WR3000S (MT7981, 256 MB RAM): 52 MB RSS for the lite
#  variant, 58 MB for the full one. The price: ads are not blocked.
#
#  The lite file is generated, not maintained by hand - that keeps it from
#  drifting away from the full config.
#
#  Usage: ./scripts/make-lite.sh
# =============================================================================
set -eu

DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$DIR/.." && pwd)"
SRC="$ROOT/RU-Mihomo.yaml"
DST="$ROOT/RU-Mihomo-lite.yaml"

[ -f "$SRC" ] || { echo "ERROR: $SRC not found"; exit 1; }

python3 - "$SRC" "$DST" <<'PYEOF'
import re, sys

src, dst = sys.argv[1], sys.argv[2]
lines = open(src, encoding="utf-8").read().split("\n")

out = []
i = 0
removed_provider = False
removed_rule = False

while i < len(lines):
    line = lines[i]

    # 1. Drop the antiad rule-provider block. It is the last block of the
    #    rule-providers section, so it ends at the next key on the same level.
    if re.match(r"^  antiad:\s*$", line):
        removed_provider = True
        i += 1
        while i < len(lines) and (lines[i].startswith("    ") or lines[i].strip() == ""):
            # stop at the blank line that separates the sections
            if lines[i].strip() == "" and i + 1 < len(lines) and not lines[i + 1].startswith("    "):
                break
            i += 1
        continue

    # 2. Drop the antiad rule and turn its comment into a note.
    if re.match(r"^  - RULE-SET,antiad,REJECT\s*$", line):
        removed_rule = True
        i += 1
        continue
    if line.strip() == "# 3. Ads.":
        out.append("  # 3. Ads - DISABLED in the lite variant (saves about 4 MB of RAM).")
        i += 1
        continue

    out.append(line)
    i += 1

if not removed_provider or not removed_rule:
    print("ERROR: the antiad block was not found in the source file", file=sys.stderr)
    sys.exit(1)

text = "\n".join(out)

# 3. Adjust the header note.
text = text.replace(
    "#  Full variant: ad blocking is ON. The smaller variant without it is\n"
    "#  RU-Mihomo-lite.yaml (generated by scripts/make-lite.sh).",
    "#  LITE VARIANT: ad blocking is disabled here, the rule-set and the rule\n"
    "#  are removed by scripts/make-lite.sh. The full config is RU-Mihomo.yaml.")

open(dst, "w", encoding="utf-8").write(text)
print(f"written: {dst}")
PYEOF

# Sanity check: the lite file must not reference antiad anymore.
if grep -q "antiad" "$DST"; then
  echo "ERROR: antiad still referenced in $DST"
  exit 1
fi

echo "OK: lite variant has no antiad references"
