#!/usr/bin/env bash
# =============================================================================
#  make-smart.sh - build RU-Mihomo-smart.yaml from RU-Mihomo.yaml
# =============================================================================
#  The smart variant is the full config for the SMART CORE: the fork
#  https://github.com/vernesong/mihomo (upstream MetaCubeX has no "smart"
#  type - "unsupported type: smart" even in v1.19.34).
#
#  What changes:
#    * the group "🚀 Auto" becomes type: smart
#    * the group "⚡ Turbo" stays a plain url-test group, so there is always a
#      fallback that does not depend on the smart core
#    * the LightGBM model options are added at the top level
#
#  The smart core needs its own binary on the router:
#    OpenClash -> "core type" = "Smart" (or set SMART_ENABLE=1 in the
#    overwrite file).
#
#  Usage: ./scripts/make-smart.sh
# =============================================================================
set -eu

DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$DIR/.." && pwd)"
SRC="$ROOT/RU-Mihomo.yaml"
DST="$ROOT/RU-Mihomo-smart.yaml"

[ -f "$SRC" ] || { echo "ERROR: $SRC not found"; exit 1; }

python3 - "$SRC" "$DST" <<'PYEOF'
import re, sys

src, dst = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8").read()

# 1. The smart group replaces the url-test group "🚀 Auto".
old_auto = """  - name: "🚀 Auto"
    type: url-test
    use:
      - Main
    exclude-filter: *foreign-filter
    url: *probe-url
    interval: *probe-interval
    tolerance: *probe-tolerance
    lazy: true
"""
new_auto = """  - name: "🚀 Auto"
    type: smart
    use:
      - Main
    exclude-filter: *foreign-filter
    url: *probe-url
    interval: *probe-interval
    tolerance: *probe-tolerance
    # Smart core options (vernesong/mihomo only):
    # priority multipliers for the node names that match, the first match wins,
    # a pattern is tried as a regex first and as a plain substring otherwise.
    policy-priority: "Premium:1.30;SG:1.15;\\bRU\\b:0.50"
    # use the LightGBM model to predict the weight of a node.
    # Needs Model.bin (9.3 MB) - see docs/DESIGN.md.
    uselightgbm: false
    # collect data for training a model of your own
    collectdata: false
    # share of the connections recorded by collectdata, 0-1
    sample-rate: 1
    # look the ASN up first when a node is chosen.
    # true makes the core download ASN.mmdb (8.7 MB of flash!) and prefer a
    # diverse ASN. Off by default: on a router with 84.8 MB of flash that
    # space is worth more elsewhere.
    prefer-asn: false
"""
if old_auto not in text:
    print("ERROR: the '🚀 Auto' group was not found in the source file", file=sys.stderr)
    sys.exit(1)
text = text.replace(old_auto, new_auto)

# 2. LightGBM model options at the top level.
old_profile = """profile:
  store-selected: true
  store-fake-ip: true
"""
new_profile = """profile:
  store-selected: true
  store-fake-ip: true
  # maximum size of the collected training data, in MB
  smart-collector-size: 100

# LightGBM model, used by the smart groups when uselightgbm is on.
# The model is 9.3 MB - on a router with little flash, leave the auto update
# off and keep uselightgbm: false.
lgbm-auto-update: false
lgbm-update-interval: 72
lgbm-url: "https://github.com/vernesong/mihomo/releases/download/LightGBM-Model/Model.bin"
"""
if old_profile not in text:
    print("ERROR: the profile block was not found in the source file", file=sys.stderr)
    sys.exit(1)
text = text.replace(old_profile, new_profile)

# 3. Header note.
text = text.replace(
    "#  Full variant: ad blocking is ON. The smaller variant without it is\n"
    "#  RU-Mihomo-lite.yaml (generated by scripts/make-lite.sh).",
    "#  SMART VARIANT: for the smart core (vernesong/mihomo). The group\n"
    "#  '🚀 Auto' is a smart group here. Generated by scripts/make-smart.sh;\n"
    "#  the plain config is RU-Mihomo.yaml.")

open(dst, "w", encoding="utf-8").write(text)
print(f"written: {dst}")
PYEOF

# Sanity check: the smart group must be there.
if ! grep -q "type: smart" "$DST"; then
  echo "ERROR: no smart group in $DST"
  exit 1
fi

echo "OK: smart variant written"
